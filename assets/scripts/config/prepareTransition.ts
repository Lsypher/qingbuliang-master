/**
 * 准备过场的节拍参数：过场（开始页／结算页 → 单局页之间那段全屏过场）要亮多久、最多亮多久。
 *
 * 文件名与常量前缀都用 `prepare`（准备过场），不用光秃秃的 `transition`：
 * `balance.ts` 里已经有一个 `SERVE_TRANSITION_MS`，那个"过渡"指的是**出餐换顾客**，与过场是两件事。
 *
 * 为什么单独一个文件而不是塞进 balance.ts：那份是**单局规则**用的数值（时长、扣时、计分），
 * 过场是纯表现层的时序，与胜负无关。两者混在一起，日后调规则的人会顺手改到过场的节拍。
 * 觉得过场"太久 / 太短"就改这里，不要改逻辑。
 */

/**
 * 最短展示时长（毫秒）：从**过场出现那一刻**起算，到点了才允许进单局页。
 * 它同时是"给玩家准备时间"的那段固定节拍——本机预载再快也不会短于它。
 */
export const PREPARE_MIN_SHOW_MS = 1_200;

/**
 * 硬超时（毫秒）：从过场出现到"必须放行"的**总时长上限**。
 * 它不看预载状态，唯一目的就是"别把玩家困在过场里"。
 */
export const PREPARE_TIMEOUT_MS = 3_000;
